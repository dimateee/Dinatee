// Рекомендуемая ФИПИ шкала: всего 31 балл, «3» — от 8 баллов, из них не меньше 2 за геометрию;
// «4» — от 15, «5» — от 22. Регион может немного менять шкалу.
export function gradeOf(total, geometry) {
  if (total >= 22 && geometry >= 2) return 5;
  if (total >= 15 && geometry >= 2) return 4;
  if (total >= 8 && geometry >= 2) return 3;
  return 2;
}
