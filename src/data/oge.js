const TRIPLES = [[3, 4, 5], [5, 12, 13], [8, 15, 17], [7, 24, 25], [6, 8, 10], [9, 12, 15], [12, 16, 20], [20, 21, 29]];
const triple = (max = 40) => {
  const [a, b, c] = pick(TRIPLES);
  const k = pick([1, 1, 2, 3].filter((x) => c * x <= max)) || 1;
  return [a * k, b * k, c * k];
};

