/* ===== 7. Числа и координатная прямая ===== */
const numberLine = [
  () => {
    const n = rnd(3, 9);
    const inside = () => { let k; do { k = rnd(n * n + 1, (n + 1) * (n + 1) - 1); } while (Number.isInteger(Math.sqrt(k))); return k; };
    const outside = (lo, hi) => { let k; do { k = rnd(lo, hi); } while (Number.isInteger(Math.sqrt(k)) || (k > n * n && k < (n + 1) * (n + 1))); return k; };
    const good = inside();
    const bad = new Set();
    while (bad.size < 3) bad.add(outside(Math.max(2, (n - 2) * (n - 2)), (n + 2) * (n + 2)));
    const opts = shuffle([good, ...bad]);
    return {
      q: `Какое из чисел принадлежит отрезку $[${n};\\ ${n + 1}]$?`,
      kind: "choice",
      options: opts.map((k) => `$\\sqrt{${k}}$`),
      answer: String(opts.indexOf(good) + 1),
      steps: [`Возведём границы в квадрат: $${n}^2 = ${n * n}$, $${n + 1}^2 = ${(n + 1) * (n + 1)}$`, `Подходит корень из числа между $${n * n}$ и $${(n + 1) * (n + 1)}$ — это $\\sqrt{${good}}$`],
    };
  },
  () => {
    let vals;
    do {
      vals = [
        { t: m(rnd(11, 89) / 100), v: 0 },
        { t: "", v: 0 }, { t: "", v: 0 }, { t: m(rnd(1, 9) / 10), v: 0 },
      ];
      const f1 = frac(rnd(1, 6), pick([3, 7, 9, 11])), f2 = frac(rnd(1, 8), pick([6, 9, 13]));
      vals[1] = { t: tex(f1), v: fVal(f1) };
      vals[2] = { t: tex(f2), v: fVal(f2) };
      vals[0].v = Number(vals[0].t.replace("{,}", "."));
      vals[3].v = Number(vals[3].t.replace("{,}", "."));
    } while (new Set(vals.map((x) => x.v.toFixed(4))).size < 4 || vals.some((x) => x.v >= 1));
    const opts = shuffle(vals);
    const best = opts.reduce((acc, x, i) => (x.v > opts[acc].v ? i : acc), 0);
    return {
      q: "Какое из чисел наибольшее?",
      kind: "choice",
      options: opts.map((x) => `$${x.t}$`),
      answer: String(best + 1),
      steps: [`Переведём всё в десятичные дроби: ${opts.map((x) => `$${x.t} \\approx ${m(Math.round(x.v * 1000) / 1000)}$`).join(", ")}`, `Наибольшее — $${opts[best].t}$`],
    };
  },
];

