const ANIMALS = ["ёж", "кот", "волк", "белка", "собака", "медведь", "черепаха", "аллигатор", "гиппопотам"];

const volume = mix(
  () => {
    // Классика ОГЭ: из перечня вычеркнули слово, размер уменьшился
    const words = shuffle(ANIMALS).slice(0, 6);
    // Вычеркнутое слово должно однозначно определяться по длине
    const unique = words.filter((w) => words.filter((x) => x.length === w.length).length === 1);
    const word = pick(unique), bytes = (word.length + 2) * 2;
    const opts = shuffle([word, ...shuffle(words.filter((w) => w !== word)).slice(0, 3)]);
    return {
      q: `В кодировке UTF-16 каждый символ кодируется 16 битами. Ученик написал текст: «${words.map((w) => w[0].toUpperCase() + w.slice(1)).join(", ")} — животные». Потом он вычеркнул одно название вместе с лишней запятой и пробелом. Размер текста уменьшился на ${plural(bytes, ["байт", "байта", "байт"])}. Какое слово вычеркнули?`,
      kind: "choice",
      options: opts.map((w) => w[0].toUpperCase() + w.slice(1)),
      answer: String(opts.indexOf(word) + 1),
      steps: ["16 бит = 2 байта на символ", `$${bytes} : 2 = ${bytes / 2}$ — столько символов вычеркнули, из них 2 — запятая и пробел`, `Длина слова: $${bytes / 2} - 2 = ${word.length}$, то есть ${plural(word.length, ["буква", "буквы", "букв"])}: это «${word}»`],
    };
  },
  () => {
    const n = pick([16, 32, 64, 128, 256, 512]), i = pick([8, 16]);
    return { q: `Текст содержит ${plural(n, ["символ", "символа", "символов"])}. Каждый символ кодируется ${i} битами. Найдите информационный объём текста в байтах.`, answer: fmt((n * i) / 8), steps: [`$${n} \\cdot ${i} = ${n * i}$ бит`, `$${n * i} : 8 = ${(n * i) / 8}$ байт`] };
  },
  () => {
    const k = pick([1, 2, 3, 4, 5, 8]);
    return Math.random() < 0.5
      ? { q: `Сколько байт в ${k} Кбайт?`, answer: fmt(k * 1024), steps: ["1 Кбайт = 1024 байта", `$${k} \\cdot 1024 = ${k * 1024}$`] }
      : { q: `Сколько бит в ${k} Кбайт?`, answer: fmt(k * 1024 * 8), steps: ["1 Кбайт = 1024 байта, 1 байт = 8 бит", `$${k} \\cdot 1024 \\cdot 8 = ${k * 8192}$`] };
  },
  () => {
    const i = rnd(2, 8);
    return { q: `Сколько различных символов можно закодировать с помощью ${i} бит?`, answer: fmt(2 ** i), steps: ["Количество кодов $N = 2^i$", `$2^{${i}} = ${2 ** i}$`] };
  },
);

const logic = mix(
  () => {
    const a = rnd(5, 20);
    const opts = shuffle([a - 2, a - 1, a, a + 1, a + 2, a + 3]).slice(0, 4);
    const good = opts.filter((x) => x >= a && x % 2 === 1);
    if (good.length !== 1) return logic();
    return {
      q: `Для какого из приведённых чисел истинно высказывание: НЕ (X < ${a}) И (X нечётное)?`,
      kind: "choice",
      options: opts.map(String),
      answer: String(opts.indexOf(good[0]) + 1),
      steps: [`НЕ (X < ${a}) — то же, что X ≥ ${a}`, `Нужно нечётное число не меньше ${a}: это ${good[0]}`],
    };
  },
  () => {
    const a = rnd(2, 15), b = a + rnd(3, 12);
    return { q: `Сколько существует целых чисел X, для которых истинно высказывание: (X > ${a}) И НЕ (X > ${b})?`, answer: fmt(b - a), steps: [`НЕ (X > ${b}) означает X ≤ ${b}`, `Подходят X от ${a + 1} до ${b}: это $${b} - ${a} = ${b - a}$ чисел`] };
  },
  () => {
    const a = rnd(10, 40);
    return { q: `Напишите наименьшее чётное число X, для которого ложно высказывание: X < ${a}.`, answer: fmt(a % 2 === 0 ? a : a + 1), steps: [`«X < ${a}» ложно, когда X ≥ ${a}`, `Наименьшее чётное из них — ${a % 2 === 0 ? a : a + 1}`] };
  },
);

const programs = mix(
  () => {
    const a = rnd(1, 5), b = rnd(6, 15), step = pick([1, 2, 3]);
    let s = 0;
    for (let k = a; k < b; k += step) s += k;
    return {
      q: "Определите, что будет напечатано в результате работы программы.",
      code: `s = 0\nfor k in range(${a}, ${b}${step > 1 ? `, ${step}` : ""}):\n    s = s + k\nprint(s)`,
      answer: fmt(s),
      steps: [`range(${a}, ${b}${step > 1 ? `, ${step}` : ""}) даёт числа: ${[...Array(Math.ceil((b - a) / step)).keys()].map((i) => a + i * step).join(", ")} (число ${b} не входит)`, `Их сумма: ${s}`],
    };
  },
  () => {
    const A = rnd(4, 9), B = rnd(4, 9), op = pick(["or", "and"]);
    const pairs = Array.from({ length: 9 }, () => [rnd(-3, 12), rnd(-3, 12)]);
    const yes = pairs.filter(([s, t]) => (op === "or" ? s > A || t > B : s > A && t > B)).length;
    return {
      q: `Программа была запущена 9 раз. В качестве значений s и t вводились пары: ${pairs.map(([s, t]) => `(${s}, ${t})`).join("; ")}. Сколько было запусков, при которых программа напечатала «YES»?`,
      code: `s = int(input())\nt = int(input())\nif s > ${A} ${op} t > ${B}:\n    print("YES")\nelse:\n    print("NO")`,
      answer: fmt(yes),
      steps: [op === "or" ? `«or» — достаточно, чтобы выполнилось хотя бы одно: s > ${A} или t > ${B}` : `«and» — должны выполниться оба: s > ${A} и t > ${B}`, `Подходящие пары: ${pairs.filter(([s, t]) => (op === "or" ? s > A || t > B : s > A && t > B)).map(([s, t]) => `(${s}, ${t})`).join("; ") || "нет"}`, `Ответ: ${yes}`],
    };
  },
  () => {
    const a = rnd(2, 5), b = pick([2, 3]), start = rnd(1, 6);
    const prog = Array.from({ length: 5 }, () => pick(["1", "2"])).join("");
    let x = start;
    const trace = [String(start)];
    for (const c of prog) { x = c === "1" ? x + a : x * b; trace.push(String(x)); }
    return {
      q: `У исполнителя Вычислитель две команды: 1. прибавь ${a}; 2. умножь на ${b}. Какое число получится из числа ${start} после выполнения программы ${prog}?`,
      answer: fmt(x),
      steps: ["Выполняем команды по очереди", trace.join(" → ")],
    };
  },
  () => {
    const n = rnd(20, 300);
    let k = 0, x = n;
    while (x > 0) { x = Math.floor(x / 2); k++; }
    return {
      q: "Что будет напечатано в результате работы программы?",
      code: `n = ${n}\nk = 0\nwhile n > 0:\n    n = n // 2\n    k = k + 1\nprint(k)`,
      answer: fmt(k),
      steps: ["Каждый шаг делит n на 2 нацело — это убирает одну двоичную цифру", `$${n}_{10} = ${n.toString(2)}_2$ — ${k} цифр, значит цикл выполнится ${k} раз`],
    };
  },
);

