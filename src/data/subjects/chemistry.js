  const [sym, name, gen, z, period, outer] = pick(EL);
  const kind = pick(["p", "e", "outer", "levels"]);
  const cap = name[0].toUpperCase() + name.slice(1);
  if (kind === "p") return { q: `Сколько протонов в ядре атома ${gen} (${sym})?`, answer: fmt(z), steps: ["Число протонов равно порядковому номеру элемента", `${cap} — элемент № ${z}`] };
