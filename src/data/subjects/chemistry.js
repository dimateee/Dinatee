const AR = { H: 1, C: 12, N: 14, O: 16, Na: 23, Mg: 24, Al: 27, Si: 28, P: 31, S: 32, Cl: 35.5, K: 39, Ca: 40, Fe: 56, Cu: 64, Zn: 65, Ba: 137, Ag: 108 };
const NAMES = { H: "водорода", C: "углерода", N: "азота", O: "кислорода", Na: "натрия", Mg: "магния", Al: "алюминия", S: "серы", Cl: "хлора", K: "калия", Ca: "кальция", Fe: "железа", Cu: "меди", P: "фосфора" };

// «Ca(OH)2» → { Ca: 1, O: 2, H: 2 }
export function parseFormula(f) {
  const stack = [{}];
  const re = /([A-Z][a-z]?|\(|\))(\d*)/g;
  let t;
  while ((t = re.exec(f))) {
    const [, tok, num] = t;
    const k = Number(num || 1);
    if (tok === "(") stack.push({});
    else if (tok === ")") {
      const group = stack.pop();
      for (const [el, c] of Object.entries(group)) stack.at(-1)[el] = (stack.at(-1)[el] || 0) + c * k;
    } else stack.at(-1)[tok] = (stack.at(-1)[tok] || 0) + k;
  }
  return stack[0];
}
export const molarMass = (f) => Object.entries(parseFormula(f)).reduce((s, [el, c]) => s + AR[el] * c, 0);
const mrSteps = (f) => {
  const parts = Object.entries(parseFormula(f)).map(([el, c]) => (c > 1 ? `${c} \\cdot ${m(AR[el])}` : m(AR[el])));
  return `$M_r(${chem(f).slice(1, -1)}) = ${parts.join(" + ")} = ${m(molarMass(f))}$`;
};

const COMPOUNDS = ["H2O", "CO2", "NaCl", "H2SO4", "HCl", "NaOH", "CaCO3", "HNO3", "Fe2O3", "CuSO4", "NH3", "CH4", "Al2O3", "MgO", "KOH", "CaO", "SO2", "SO3", "P2O5", "Ca(OH)2", "Na2CO3", "K2SO4", "ZnCl2", "Mg(OH)2"];

const calc = mix(
  () => {
    const f = pick(COMPOUNDS);
    return { q: `Вычислите относительную молекулярную массу ${chem(f)}.`, answer: fmt(molarMass(f)), steps: ["Складываем атомные массы всех атомов, умножая на индексы", mrSteps(f)] };
  },
  () => {
    const f = pick(COMPOUNDS);
    const comp = parseFormula(f);
    const el = pick(Object.keys(comp).filter((x) => NAMES[x]));
    const w = Math.round(((AR[el] * comp[el]) / molarMass(f)) * 100);
    return {
      q: `Вычислите массовую долю ${NAMES[el]} в ${chem(f)} (в процентах). Ответ округлите до целых.`,
      answer: fmt(w),
      steps: [mrSteps(f), `$\\omega = \\frac{${comp[el] > 1 ? `${comp[el]} \\cdot ` : ""}${m(AR[el])}}{${m(molarMass(f))}} \\cdot 100\\% \\approx ${w}\\%$`],
    };
  },
  () => {
    const f = pick(["H2O", "CO2", "NaOH", "CaCO3", "NaCl", "H2SO4", "O2", "CH4", "MgO"]), M = molarMass(f), n = pick([0.25, 0.5, 2, 3, 4]);
    return { q: `Какое количество вещества (в моль) содержится в ${fmt(M * n)} г ${chem(f)}?`, answer: fmt(n), steps: [`$M(${chem(f).slice(1, -1)}) = ${m(M)}$ г/моль`, `$n = \\frac{m}{M} = \\frac{${m(M * n)}}{${m(M)}} = ${m(n)}$ моль`] };
  },
  () => {
    const n = pick([0.5, 1.5, 2, 3, 5]), gas = pick(["кислорода", "азота", "водорода", "углекислого газа"]);
    return { q: `Какой объём (в литрах, н. у.) занимают ${fmt(n)} моль ${gas}?`, answer: fmt(22.4 * n), steps: ["Молярный объём любого газа при н. у. — 22,4 л/моль", `$V = n \\cdot V_m = ${m(n)} \\cdot 22{,}4 = ${m(22.4 * n)}$ л`] };
  },
);

