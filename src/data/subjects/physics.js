const electricity = mix(
  () => {
    const R = pick([2, 4, 5, 10, 20, 50]), I = pick([0.2, 0.5, 1, 1.5, 2, 3]);
    return { q: `Сопротивление резистора ${R} Ом, сила тока в нём ${fmt(I)} А. Найдите напряжение на резисторе (в В).`, answer: fmt(R * I), steps: ["Закон Ома: $I = \\frac{U}{R}$, значит $U = IR$", `$U = ${m(I)} \\cdot ${R} = ${m(R * I)}$ В`] };
  },
  () => {
    const U = pick([6, 12, 24, 36, 220]), R = pick([2, 3, 4, 6, 12].filter((r) => (U / r) * 10 === Math.round((U / r) * 10)));
    return { q: `На резистор сопротивлением ${R} Ом подано напряжение ${U} В. Найдите силу тока (в А).`, answer: fmt(U / R), steps: ["$I = \\frac{U}{R}$", `$I = \\frac{${U}}{${R}} = ${m(U / R)}$ А`] };
  },
  () => {
    const [a, b] = pick([[6, 3], [12, 4], [10, 10], [20, 5], [30, 15], [12, 6], [60, 30]]);
    return Math.random() < 0.5
      ? { q: `Два резистора сопротивлением ${a} Ом и ${b} Ом соединены последовательно. Найдите общее сопротивление (в Ом).`, answer: fmt(a + b), steps: ["При последовательном соединении $R = R_1 + R_2$", `$R = ${a} + ${b} = ${a + b}$ Ом`] }
      : { q: `Два резистора сопротивлением ${a} Ом и ${b} Ом соединены параллельно. Найдите общее сопротивление (в Ом).`, answer: fmt((a * b) / (a + b)), steps: ["При параллельном соединении $R = \\frac{R_1 R_2}{R_1 + R_2}$", `$R = \\frac{${a} \\cdot ${b}}{${a} + ${b}} = \\frac{${a * b}}{${a + b}} = ${m((a * b) / (a + b))}$ Ом`] };
  },
  () => {
    const P = pick([1, 1.5, 2, 3]), t = pick([15, 30, 45, 60, 90, 120]);
    return { q: `Электрический чайник мощностью ${fmt(P)} кВт работал ${t} минут. Сколько электроэнергии (в кВт·ч) он израсходовал?`, answer: fmt((P * t) / 60), steps: [`${t} мин $= ${m(t / 60)}$ ч`, `$A = Pt = ${m(P)} \\cdot ${m(t / 60)} = ${m((P * t) / 60)}$ кВт·ч`] };
  },
  () => {
    const U = pick([12, 24, 220]), I = pick([0.5, 2, 5, 10]);
    return { q: `Прибор работает при напряжении ${U} В, сила тока в нём ${fmt(I)} А. Найдите мощность прибора (в Вт).`, answer: fmt(U * I), steps: ["$P = UI$", `$P = ${U} \\cdot ${m(I)} = ${m(U * I)}$ Вт`] };
  },
);

